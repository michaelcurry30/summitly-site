#!/usr/bin/env node
// make_dojo.mjs — Habit Dojo assembler (rules: DOJO_BIBLE.md; renderer: kit/dojo.js)
//   node make_dojo.mjs <project> <spec.json>      write <project>/{index.html, spec.json, sound.json, kit -> ../kit}
//   node make_dojo.mjs <project> --queue N         take spec N (0-based) from dojo_queue.json
// Then: node render.mjs <project> ; node kit/check_overlap.mjs <project> --step 0.1 ; python3 kit/sound/mix.py <project>
// spec.json = {"name": "dojo-q01", "hook": "5 habits that fix your morning", "items": ["...", ...4-6], "lesson": "...",
//              "cta": "📒 FREE HABIT TRACKER · LINK IN BIO", "music_seed": 3, optional "mood" (hype|chill), "key", "bpm"}
import { readFileSync, writeFileSync, mkdirSync, existsSync, symlinkSync } from 'node:fs';
import { resolve, join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const WS = dirname(fileURLToPath(import.meta.url));
const die = m => { console.error('make_dojo: ' + m); process.exit(1); };
const win = {};
vm.runInNewContext(readFileSync(join(WS, 'kit/dojo.js'), 'utf8'), { window: win, Math, Object, Array, Error, parseInt, JSON, String });
const D = win.Dojo;
const args = process.argv.slice(2);
if (args.length < 2) die('usage: node make_dojo.mjs <project> <spec.json> | <project> --queue N');
const pdir = resolve(WS, args[0]);
let spec;
if (args[1] === '--queue') {
  const q = JSON.parse(readFileSync(join(WS, 'dojo_queue.json'), 'utf8'));
  spec = (q.specs || q)[+args[2]]; if (!spec) die('no queue entry ' + args[2]);
} else spec = JSON.parse(readFileSync(resolve(WS, args[1]), 'utf8'));

// ---- validate (DOJO_BIBLE rules)
const DEFAULT_CTA = '📒 FREE HABIT TRACKER · LINK IN BIO';
if (!spec.hook || !Array.isArray(spec.items) || !spec.lesson) die('spec needs hook, items[], lesson');
if (spec.items.length < 4 || spec.items.length > 6) die('use 4-6 items');
if (spec.hook.length > 44) die(`hook is ${spec.hook.length} chars (max 44)`);
spec.items.forEach((s, i) => { if (typeof s !== 'string' || !s.trim()) die(`item ${i + 1} is empty`); if (s.length > 30) die(`item ${i + 1} "${s}" is ${s.length} chars (max 30, aim <= 28)`); });
if (spec.lesson.length > 72) die(`lesson is ${spec.lesson.length} chars (max 72)`);
spec.cta = spec.cta || DEFAULT_CTA;
if (spec.cta.length > 46) die(`cta is ${spec.cta.length} chars (max 46)`);
const T = D.timeline(spec);
if (T.DUR < 18 || T.DUR > 24) die(`total ${T.DUR.toFixed(2)} s is outside 18-24 s`);

// ---- project folder
mkdirSync(pdir, { recursive: true });
if (!existsSync(join(pdir, 'kit'))) symlinkSync('../kit', join(pdir, 'kit'));
const specPath = join(pdir, 'spec.json');
if (resolve(WS, args[1] || '') !== specPath) writeFileSync(specPath, JSON.stringify(spec, null, 2) + '\n');
const esc = s => JSON.stringify(s).replace(/</g, '\\u003c');
writeFileSync(join(pdir, 'index.html'), `<!doctype html>
<html><head><meta charset="utf-8"><title>${spec.hook.replace(/[<&"*]/g, '')}</title>
<!-- generated by make_dojo.mjs from spec.json: do not hand-edit (change spec.json or kit/dojo.js and re-run) -->
<script src="kit/dojo.js"></script></head>
<body><div id="stage"></div>
<script>
const SPEC = ${esc(spec)};
Dojo.assemble(SPEC);
</script></body></html>
`);

// ---- sound: upbeat bed + cut-in whoosh / pop per item + ninja reaction + lesson chime + CTA pop + loop whoosh
const r2 = x => Math.round(x * 100) / 100;
const seed = +spec.music_seed || 1;
const sfx = [
  { t: 0, name: 'shing', gain: -16 },
  { t: 1.12, name: 'whoosh_short', gain: -13 },
];
for (const it of T.items) {
  sfx.push({ t: r2(it.a + .14), name: 'whoosh_short', gain: -10, pitch: it.i % 2 ? 1 : 0 });
  sfx.push({ t: r2(it.a + .23), name: 'pop', gain: -5, pitch: it.i });
  if (it.react === 'slash') sfx.push({ t: r2(it.a - .1), name: 'shing', gain: -15, pitch: 2 });
  if (it.react === 'bounce') sfx.push({ t: r2(it.a - .07), name: 'hop', gain: -14 });
  if (it.react === 'flick') sfx.push({ t: r2(it.a - .1), name: 'ui_tap', gain: -14, pitch: 3 });
}
sfx.push({ t: r2(T.lessonAt), name: 'chime_up', gain: -8 }, { t: r2(T.ctaAt), name: 'pop', gain: -6, pitch: 7 },
  { t: r2(T.backAt + .25), name: 'whoosh_long', gain: -15 });
sfx.sort((a, b) => a.t - b.t);
const KEYS = ['A minor', 'C major', 'E minor', 'G major', 'D minor', 'F major'];
const mood = spec.mood || (seed % 2 ? 'hype' : 'chill');
const bpm = spec.bpm || (mood === 'hype' ? 112 + (seed * 3) % 12 : 88 + seed % 6);
const sound = { voice: 'af_heart', vo: [], sfx,
  music: { mood, bpm, key: spec.key || KEYS[seed % KEYS.length], hit: r2(T.lessonAt), seed, gain: mood === 'hype' ? -9 : -7 } };
writeFileSync(join(pdir, 'sound.json'), JSON.stringify(sound, null, 1) + '\n');
console.log(`make_dojo ${basename(pdir)}: ${T.items.length} items @ ${T.items.map(i => i.a.toFixed(1)).join(' ')} | lesson@${T.lessonAt.toFixed(1)} | total ${T.DUR.toFixed(2)} s | ${mood} ${bpm} bpm, ${sfx.length} sfx`);
console.log(`next: node render.mjs ${basename(pdir)} ; node kit/check_overlap.mjs ${basename(pdir)} --step 0.1 ; python3 kit/sound/mix.py ${basename(pdir)}`);
