#!/usr/bin/env node
// make_quiet.mjs — Quiet Progress assembler (rules: QUIET_BIBLE.md; scene library: kit/quiet.js Quiet.SCENES)
//   node make_quiet.mjs <project> <spec.json>        write <project>/{index.html, spec.json, sound.json, kit -> ../kit}
//   node make_quiet.mjs <project> --queue N           take spec N (0-based) from quiet_queue.json
//   node make_quiet.mjs --list                        list the scene ids, default labels and durations
// Then: node render.mjs <project> && node kit/check_overlap.mjs <project> --step 0.1 && python3 kit/sound/mix.py <project>
// spec.json = {"hook": "...", "scenes": [{"id": "...", "labels": {"a": "..."}}, ...], "closing": "...", "music_seed": 3,
//              optional: "cta", "key" ("D major"), "bpm" (72), "watermark" (text or false), "close" (closing beat s, 5.2)}
import { readFileSync, writeFileSync, mkdirSync, existsSync, symlinkSync, copyFileSync } from 'node:fs';
import { resolve, join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const WS = dirname(fileURLToPath(import.meta.url));
const die = m => { console.error('make_quiet: ' + m); process.exit(1); };
const win = {};
vm.runInNewContext(readFileSync(join(WS, 'kit/quiet.js'), 'utf8'), { window: win, Math, Object, Array, Error, parseInt, JSON });
const Q = win.Quiet;
const args = process.argv.slice(2);

if (args[0] === '--list') {
  for (const [id, s] of Object.entries(Q.SCENES)) console.log(`${id.padEnd(30)} ${String(s.dur).padEnd(4)} ${JSON.stringify(s.labels)}  — ${s.title}`);
  process.exit(0);
}
if (args.length < 2) die('usage: node make_quiet.mjs <project> <spec.json> | <project> --queue N | --list');
const pdir = resolve(WS, args[0]);
let spec;
if (args[1] === '--queue') {
  const q = JSON.parse(readFileSync(join(WS, 'quiet_queue.json'), 'utf8'));
  spec = (q.specs || q)[+args[2]]; if (!spec) die('no queue entry ' + args[2]);
} else spec = JSON.parse(readFileSync(resolve(WS, args[1]), 'utf8'));

// ---- validate (QUIET_BIBLE rules)
if (!spec.hook || !spec.closing || !Array.isArray(spec.scenes)) die('spec needs hook, scenes[], closing');
if (spec.scenes.length < 4 || spec.scenes.length > 5) die('use 4-5 scenes');
const words = s => (s || '').split(/\s+/).filter(Boolean).length;
if (words(spec.hook) > 6) die('hook must be <= 6 words');
if (words(spec.closing) > 6) die('closing must be <= 6 words');
for (const s of spec.scenes) {
  const d = Q.SCENES[s.id]; if (!d) die(`unknown scene id "${s.id}" (node make_quiet.mjs --list)`);
  const L = Object.assign({}, d.labels, s.labels || {});
  for (const k of Object.keys(s.labels || {})) if (!(k in d.slots)) die(`scene ${s.id} has no label slot "${k}" (slots: ${Object.keys(d.slots).join(', ')})`);
  const n = Object.keys(d.slots).reduce((m, k) => m + words(L[k]), 0);
  if (n > 6) die(`scene ${s.id}: ${n} words of labels (max 6)`);
}
const T = Q.timeline(spec);
if (T.DUR < 25 || T.DUR > 40) die(`total ${T.DUR.toFixed(2)} s is outside 25-40 s`);

// ---- project folder
mkdirSync(pdir, { recursive: true });
if (!existsSync(join(pdir, 'kit'))) symlinkSync('../kit', join(pdir, 'kit'));
const specPath = join(pdir, 'spec.json');
if (resolve(WS, args[1] || '') !== specPath) writeFileSync(specPath, JSON.stringify(spec, null, 2) + '\n');
const esc = s => JSON.stringify(s).replace(/</g, '\\u003c');
writeFileSync(join(pdir, 'index.html'), `<!doctype html>
<html><head><meta charset="utf-8"><title>${(spec.hook || 'Quiet Progress').replace(/[<&"]/g, '')}</title>
<!-- generated by make_quiet.mjs from spec.json: do not hand-edit (change spec.json or kit/quiet.js and re-run) -->
<script src="kit/quiet.js"></script></head>
<body><div id="stage"></div>
<script>
const SPEC = ${esc(spec)};
Quiet.assemble(SPEC);
</script></body></html>
`);

// ---- sound: calm bed + per-scene cues + transitions + closing
const sfx = [];
const r2 = x => Math.round(x * 100) / 100;
T.scenes.forEach((s, i) => {
  if (i > 0) sfx.push({ t: r2(s.a), name: 'air', gain: -15 });
  for (const [lt, name, gain, pitch] of Q.SCENES[s.id].sfx || []) {
    const t = s.a + lt; if (t > T.DUR - .3 || (i < T.scenes.length - 1 && lt > s.dur + .2)) continue;
    const c = { t: r2(t), name, gain }; if (pitch) c.pitch = pitch; sfx.push(c);
  }
});
sfx.push({ t: r2(T.closeAt + .15), name: 'soft_chime', gain: -12 }, { t: r2(T.ctaAt), name: 'soft_tap', gain: -16, pitch: 7 });
sfx.sort((a, b) => a.t - b.t);
const sound = { voice: 'af_heart', vo: [], sfx,
  music: { mood: 'calm', bpm: spec.bpm || 72, key: spec.key || 'D major', hit: r2(T.closeAt), seed: spec.music_seed || 1, gain: -7 } };
writeFileSync(join(pdir, 'sound.json'), JSON.stringify(sound, null, 1) + '\n');
console.log(`make_quiet ${basename(pdir)}: ${T.scenes.map(s => `${s.id}@${s.a.toFixed(1)}`).join(' | ')} | closing@${T.closeAt.toFixed(1)}  total ${T.DUR.toFixed(2)} s, ${sfx.length} sfx cues`);
console.log(`next: node render.mjs ${basename(pdir)} && node kit/check_overlap.mjs ${basename(pdir)} --step 0.1 && python3 kit/sound/mix.py ${basename(pdir)}`);
